// In-memory Postgres only. Run with PGLITE_MODULE pointing at the installed QA package.
const assert = require('node:assert/strict')
const { read } = require('./test-recreate.cjs')
async function main() {
  const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite')
  const db = new PGlite()
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql as $$ select null::uuid $$;`)
  await db.exec(read('supabase/migrations/20260929190000_clips.sql'))
  await db.exec(read('supabase/migrations/20261109221645_recreate_internal.sql'))
  const user = '11111111-2222-3333-4444-555555555555'
  await db.query('insert into auth.users values ($1)', [user])
  const insert = async (key, credits = 40, model = 'minimax/h3-max/recast', seconds = 10) => db.query(`insert into public.clips(user_id,idempotency_key,fingerprint,billing_reference,engine,mode,model,seconds,aspect,prompt,credits) values($1,$2,'fixture',$3,'h3','image',$4,$5,'image','fixture',$6) returning id`, [user,key,`clips-${key}`,model,seconds,credits])
  await insert('fixture-paid-10s-01')
  await insert('fixture-paid-10s-02')
  await assert.rejects(insert('fixture-paid-10s-01'), e => e.code === '23505')
  await assert.rejects(insert('fixture-free-01', 0), e => e.code === '23514')
  await assert.rejects(insert('fixture-wrong-01', 0, 'some-other-model'), e => e.code === '23514')
  await assert.rejects(insert('fixture-wrong-02', 0, 'minimax/h3-max/recast', 15), e => e.code === '23514')
  await insert('fixture-paid-15s-01', 60, 'minimax/h3-max/recast', 15)
  await db.query(`insert into public.recreate_likes(format_id,user_id) values ('outfit-morph',$1)`, [user])
  await assert.rejects(db.query(`insert into public.recreate_likes(format_id,user_id) values ('outfit-morph',$1)`, [user]), e => e.code === '23505')
  const count = await db.query(`select count(*)::int as count from public.recreate_likes where format_id='outfit-morph'`)
  assert.equal(count.rows[0].count, 1)
  for (const role of ['anon', 'authenticated']) {
    await db.exec(`set role ${role}`)
    await assert.rejects(db.query('select * from public.recreate_reports'), e => e.code === '42501')
    await assert.rejects(db.query('select * from public.recreate_likes'), e => e.code === '42501')
    await db.exec('reset role')
  }
  const rls = await db.query(`select relname, relrowsecurity from pg_class where relname in ('recreate_likes','recreate_reports')`)
  assert(rls.rows.length === 2 && rls.rows.every(r => r.relrowsecurity))
  await db.exec(read('docs/recreate-1011/PREFLIGHT-PUBLICACAO.sql'))
  await db.close()
  console.log('PASS: migration in isolated Postgres; zero-cost rows rejected, repeat paid generations allowed, request idempotency preserved, paid 40/60 rows, unique real likes, RLS and denied anon/authenticated access.')
}
main().catch(e => { console.error(e); process.exitCode = 1 })
