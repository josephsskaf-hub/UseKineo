// Actual customer component through the existing offline hook/transport boundary.
// Called by the sample guardian with runEscolhaUiProof({ current:true, scenario:adsSampleUiScenario2410 }).
import assert from 'node:assert/strict'

export async function adsSampleUiScenario2410({ client, nodeText, check }) {
  const ID = '00000000-0000-4000-8000-000000000001', PAID = '00000000-0000-4000-8000-000000000002'
  const stills = [1, 2].map(n => ({ id: `s${n}`, url: `https://offline.invalid/${n}.png` }))
  const ui = client({ internalControls: false, sampleAvailable: true, initialSample: true })
  ui.render()
  check(ui.requests.length === 0, 'sample never submits before a customer action')
  check(ui.nodes().map(nodeText).join(' ').includes('Amostra grátis'), 'free entry opens the sample')
  ui.responses.push([201, { order_id: ID, stage: 'planned', sample: true, credits: 0, max_photo_rounds: 1 }])
  await ui.click('Confirmar escolhas')
  assert.equal(ui.requests.at(-1).body.sample, true)
  assert.equal(ui.requests.at(-1).body.rota, 'kling3')
  assert.equal(ui.requests.at(-1).body.voice_mode, 'narrated')
  ui.responses.push([200, { order_id: ID, stage: 'choose', sample: true, stills, photo_round: 1, max_photo_rounds: 1 }])
  await ui.click('Preparar duas')
  check(ui.nodes().filter(n => n.type === 'input' && n.props.name === 'ace-still').length === 2, 'sample displays two stills')
  check(!ui.nodes().some(n => n.type === 'button' && nodeText(n).includes('outra rodada')), 'sample cannot request another still round')
  ui.nodes().find(n => n.type === 'input' && n.props.value === 's2').props.onChange()
  ui.render()
  ui.responses.push([202, { order_id: ID, sample: true }])
  await ui.click('Gerar minha amostra grátis')
  assert.equal(ui.requests.at(-1).body.still_id, 's2', 'the selected sample reference is preserved')
  const delivered = { order_id: ID, status: 'delivered', sample: true, presenter_id: 'amara', scenario_id: 'footwear_beach', video: { video_url: 'https://offline.invalid/sample.mp4' }, selected_still_id: 's2', stills }
  ui.responses.push([200, delivered])
  await ui.poll()
  check(ui.states[1] === 'delivered', 'status exposes the delivered sample')
  ui.responses.push([402, { error: 'out_of_credits', needed: 41, balance: 0 }])
  await ui.click('Gerar a versão completa')
  check(ui.states[2] === ID && ui.states[4] === 's2' && ui.states[1] === 'delivered', '402 retains the result and exact selected reference')
  assert.deepEqual(Object.keys(ui.requests.at(-1).body).sort(), ['order_id', 'stage'], 'upgrade cannot silently replace presenter, scenario or product')
  check(ui.nodes().filter(n => n.type === 'a' && String(n.props.href).includes(`ads_sample_order=${ID}`)).length === 4, 'all plan checkout links retain the sample order UUID')
  check(ui.nodes().map(nodeText).join(' ').includes('41 créditos'), 'upgrade explains the complete credit amount rather than the free sample price')
  check(ui.nodes().map(nodeText).join(' ').includes('12 anúncios de 15 s/mês'), 'Business capacity follows 500 monthly credits divided by the 41-credit full ad')
  ui.responses.push([403, { error: 'ads_sample_account_blocked' }])
  await ui.click('Gerar a versão completa')
  check(ui.states[2] === ID && ui.states[8].endsWith('sample.mp4'), 'eligibility refusal retains the delivered order and video')

  const linked = client({ internalControls: false, sampleAvailable: true, query: `?order=${ID}` })
  linked.render()
  linked.responses.push([200, delivered])
  await linked.poll()
  check(linked.nodes().some(n => n.type === 'button' && nodeText(n).includes('Gerar a versão completa')), 'order URL rehydrates sample upsell without local storage')
  const returned = client({ internalControls: false, sampleAvailable: true, query: `?order=${ID}&upgrade=1` })
  returned.render()
  returned.responses.push([200, delivered], [202, { order_id: PAID, status: 'generating', sample: false }])
  await returned.poll()
  await Promise.resolve()
  returned.render()
  check(returned.requests.filter(r => r.body?.stage === 'upgrade').length === 1, 'checkout return resumes exactly one upgrade')
  check(returned.states[2] === PAID && returned.states[1] === 'rendering', 'checkout return follows the new paid order')
  const paid = client({ internalControls: false, sampleAvailable: true })
  paid.render()
  await paid.click('Amostra grátis')
  check(paid.nodes().map(nodeText).join(' ').includes('2 fotos'), 'paid customers can choose the free sample')
  const cap = client({ internalControls: false, sampleAvailable: true, initialSample: true })
  cap.render()
  cap.responses.push([429, { error: 'ads_sample_cap' }])
  await cap.click('Confirmar escolhas')
  check(cap.nodes().map(nodeText).join(' ').includes('As amostras de hoje acabaram — volte amanhã ou gere a versão completa'), 'daily budget refusal has the approved customer message')
}
